#!/usr/bin/env node
// Writes apps/mobile/.env: Supabase URL (from apps/api/.env), the publishable
// key (asked), and the API URL using this Mac's Wi-Fi address so a phone on the
// same network can reach the dev API. Only public values go in this file.
// Run from the repo root: pnpm setup:mobile
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';
import { createInterface } from 'node:readline/promises';

const API_ENV = 'apps/api/.env';
const MOBILE_ENV = 'apps/mobile/.env';

function readVar(file, name) {
  if (!existsSync(file)) return undefined;
  return readFileSync(file, 'utf8').match(new RegExp(`^${name}=(.*)$`, 'm'))?.[1]?.trim();
}

function lanAddress() {
  const candidates = [];
  for (const [name, addresses] of Object.entries(networkInterfaces())) {
    for (const address of addresses ?? []) {
      if (address.family === 'IPv4' && !address.internal) candidates.push({ name, ip: address.address });
    }
  }
  // en0 is Wi-Fi on most Macs.
  return (candidates.find((c) => c.name === 'en0') ?? candidates[0])?.ip;
}

const supabaseUrl = readVar(API_ENV, 'SUPABASE_URL');
if (!supabaseUrl || supabaseUrl.includes('YOUR-PROJECT-REF')) {
  console.error(`SUPABASE_URL is missing in ${API_ENV}. Set up the API first.`);
  process.exit(1);
}
const port = readVar(API_ENV, 'PORT') || '3000';
const existingKey = readVar(MOBILE_ENV, 'EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY');

const rl = createInterface({ input: process.stdin, output: process.stdout });
console.log('\nPublishable key: Supabase dashboard -> Project Settings -> API Keys (starts with sb_publishable_).');
let key = (
  await rl.question(
    existingKey && !existingKey.endsWith('xxx')
      ? 'Publishable key (press Enter to keep the current one): '
      : 'Publishable key: ',
  )
).trim();
if (!key && existingKey) key = existingKey;
if (!key.startsWith('sb_publishable_')) {
  rl.close();
  console.error(
    key.startsWith('sb_secret_')
      ? '\nThat is a SECRET key. It must never go into the app. Copy the publishable key instead.'
      : '\nThat does not look like a publishable key (it should start with sb_publishable_).',
  );
  process.exit(1);
}

const ip = lanAddress();
const suggested = ip ? `http://${ip}:${port}` : `http://localhost:${port}`;
const apiUrl =
  (await rl.question(`API URL [${suggested}] (press Enter to accept): `)).trim() || suggested;
rl.close();

writeFileSync(
  MOBILE_ENV,
  [
    '# Generated by `pnpm setup:mobile`. Public values only; compiled into the app.',
    `EXPO_PUBLIC_SUPABASE_URL=${supabaseUrl}`,
    `EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${key}`,
    `EXPO_PUBLIC_API_URL=${apiUrl}`,
    '',
  ].join('\n'),
);
console.log(`\nSaved ${MOBILE_ENV} (API: ${apiUrl}).`);
if (!ip) console.log('No Wi-Fi address found; the phone will not reach localhost. Connect to Wi-Fi and rerun.');
